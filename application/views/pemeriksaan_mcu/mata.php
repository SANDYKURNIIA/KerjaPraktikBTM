    function insertMata() {


        $().ready(function() {
            $.ajax({
                url: "<?php echo base_url() ?>Pemeriksaan_fisik_mcu/cetak_mata",
                method: "POST",
                dataType: 'json',
                data: {
                    sklera_kiri: $('input[name="sklera_kiri"]:checked').val(),
                    sklera_kanan: $('input[name="sklera_kanan"]:checked').val(),
                    tajam_kiri: $('input[name="tajam_kiri"]').val(),
                    tajam_kanan: $('input[name="tajam_kanan"]').val(),
                    bola_mata_kiri: $('input[name="bola_mata_kiri"]:checked').val(),
                    bola_mata_kanan: $('input[name="bola_mata_kanan"]:checked').val(),
                    konjungtive_kiri: $('input[name="konjungtive_kiri"]:checked').val(),
                    konjungtive_kanan: $('input[name="konjungtive_kanan"]:checked').val(),
                    kornea_kiri: $('input[name="kornea_kiri"]:checked').val(),
                    kornea_kanan: $('input[name="kornea_kanan"]:checked').val(),
                    iris_kiri: $('input[name="iris_kiri"]:checked').val(),
                    iris_kanan: $('input[name="iris_kanan"]:checked').val(),
                    pupil_kiri: $('input[name="pupil_kiri"]:checked').val(),
                    pupil_kanan: $('input[name="pupil_kanan"]:checked').val(),
                    lensa_kiri: $('input[name="lensa_kiri"]:checked').val(),
                    lensa_kanan: $('input[name="lensa_kanan"]:checked').val(),
                    lapang_pandang_kiri: $('input[name="lapang_pandang_kiri"]:checked').val(),
                    lapang_pandang_kanan: $('input[name="lapang_pandang_kanan"]:checked').val(),
                    kedalaman_penglihatan_kiri: $('input[name="kedalaman_penglihatan_kiri"]:checked').val(),
                    kedalaman_penglihatan_kanan: $('input[name="kedalaman_penglihatan_kanan"]:checked').val(),
                    jaeger_test_kiri: $('input[name="jaeger_test_kiri"]:checked').val(),
                    jaeger_test_kanan: $('input[name="jaeger_test_kanan"]:checked').val(),
                    buta_warna: $('input[name="buta_warna"]:checked').val(),
                    lain_lain_kiri: $('#lain_lain_kiri').val(),
                    lain_lain_kanan: $('#lain_lain_kanan').val(),
                    catatan: $('#catatan').val(),
                    id_mcu: $('#id_mcu_form').val(),
                    dokter_periksa: $('#dokter_periksa').val(),
                },
                success: function(data) {
                    if (data.status == "success") {
                        swal({
                            title: "Good job!",
                            type: "success",
                            text: "Data Medical Check Up Pasien ini telah disimpan",
                            confirmButtonColor: "#3cb878",
                        }, function() {
                            location.reload();
                        });
                    } else {
                        swal({
                            title: "Gagal!",
                            type: "warning",
                            text: data.status,
                            confirmButtonColor: "#3cb878",
                        });
                    }
                }
            });
        });

        return false;
    }

    $(document).ready(function() {
        id_pelayanan = $('#id_mcu_form').val();
        $.ajax({
            url: "<?php echo base_url() ?>Pemeriksaan_fisik_mcu/get_data_pemeriksaan",
            method: "POST",
            dataType: 'json',
            data: {
                id: id_pelayanan,
                table: 'pemeriksaan_mata_mcu',
            },
            success: function(data) {
                if (data.status_dt == 'found') {
                    // Ikterik Pada Sklera
                    $('input[name="sklera_kiri"][value="' + data.sklera_kiri + '"]').prop("checked", true);
                    $('input[name="sklera_kanan"][value="' + data.sklera_kanan + '"]').prop("checked", true);

