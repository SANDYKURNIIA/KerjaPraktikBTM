                    $('input[name="konjungtive_kanan"][value="' + data.konjungtive_kanan + '"]').prop("checked", true);

                    // Kornea
                    $('input[name="kornea_kiri"][value="' + data.kornea_kiri + '"]').prop("checked", true);
                    $('input[name="kornea_kanan"][value="' + data.kornea_kanan + '"]').prop("checked", true);

                    // Iris
