function pilih(id){
	$.ajax({
		type: "POST",
		url:"<?= base_url("Formulir_Monitoring_Mengelolaan_Limbah_Benda_Tajam/getData") ?>",
		data: {
			id:id
		},
		beforeSend:function(){
			//Smooth Scroll
			window.scrollTo({
				top:0,
				behavior:'smooth'
			});
		},
		dataType: "JSON",
		success: function (res) {
			if(res != 0){
				$("#tglForm").val(res.Tanggal);
				$('#unit').val(res.unit);
				$('#idP').val(btoa(res.id_benda_tajam));
				$("input[type='radio'][name='Tersedia_fasilitas_pembuangan_sampah_yang_sesuai'][value='"+res.Tersedia_fasilitas_pembuangan_sampah_yang_sesuai+"']").prop('checked',true);
