				$("input[type='radio'][name='Tidak_ada_limbah_benda_tajam_yang_keluar_dari_tempat'][value='"+res.Tidak_ada_limbah_benda_tajam_yang_keluar_dari_tempat+"']").prop('checked',true);
				$("input[type='radio'][name='Limbah_benda_tajam_langsung_dibuang_ke_tempat_limbah_benda_tajam'][value='"+res.Limbah_benda_tajam_langsung_dibuang_ke_tempat_limbah_benda_tajam+"']").prop('checked',true);
				$("input[type='radio'][name='Jika_sudah_penuh_tempat_limbah_benda_tajam_ditutup_rapat'][value='"+res.Jika_sudah_penuh_tempat_limbah_benda_tajam_ditutup_rapat+"']").prop('checked',true);
				$("input[type='radio'][name='Tersedia_alur_pajanan'][value='"+res.Tersedia_alur_pajanan+"']").prop('checked',true);
