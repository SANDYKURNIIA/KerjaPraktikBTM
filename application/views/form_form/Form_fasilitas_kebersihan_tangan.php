function pilih(id){
	$.ajax({
		type: "POST",
		url:"<?= base_url("Formulir_fasilitas_kebersihan_tangan/getData") ?>",
		data: {
			id:id
		},
		beforeSend:function(){
			//Smooth Scroll
			window.scrollTo({
				top:0,
				behavior:'smooth'
			});
		},
		dataType: "json",
		success: function (res) {
			if(res != 0){
				$("#idP").val(btoa(res.idform_fasKeb));
                $("#nama").val(res.nama);
                $("#hasil").val(res.hasil);

				$("input[type='radio'][name='ter_saca'][value='"+res.ter_saca+"']").prop('checked',true);
                $("input[type='radio'][name='ter_caba'][value='"+res.ter_caba+"']").prop('checked',true);
				$("input[type='radio'][name='was_be'][value='"+res.was_be+"']").prop('checked',true);
				$("input[type='radio'][name='fas_cut'][value='"+res.fas_cut+"']").prop('checked',true);
				$("input[type='radio'][name='tmp_smph'][value='"+res.tmp_smph+"']").prop('checked',true);
				$("input[type='radio'][name='ter_hand'][value='"+res.ter_hand+"']").prop('checked',true);
				$("input[type='radio'][name='ter_pos'][value='"+res.ter_pos+"']").prop('checked',true);
                $("#keterangan").val(res.keterangan);
                $("#rekomendasi").val(res.rekomendasi);

				$("#btnUpdate").show();
				$("#btnSimpan").hide();
			}else{
				swal({
					title: "Gagal!",
					type: "warning",
					text: "Data Tidak Ada",
					confirmButtonColor: "#3cb878",
				});
			}
		}
	});
}

