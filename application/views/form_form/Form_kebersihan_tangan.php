function pilih(id){
	$.ajax({
		type: "POST",
		url:"<?= base_url("Formulir_kebersihan_tangan/getData") ?>",
		data: {
			id:id
		},
		beforeSend:function(){
			//Smooth Scroll
			window.scrollTo({
				top:0,
				behavior:'smooth'
			});
		},
		dataType: "json",
		success: function (res) {
			if(res != 0){
				$("#idP").val(btoa(res.id_form));
                $("#nama").val(res.nama);
                $("#hasil").val(res.hasil);

				$("input[type='radio'][name='seb_kop'][value='"+res.seb_kop+"']").prop('checked',true);
                $("input[type='radio'][name='seb_tinAnt'][value='"+res.seb_tinAnt+"']").prop('checked',true);
				$("input[type='radio'][name='set_caiTu'][value='"+res.set_caiTu+"']").prop('checked',true);
				$("input[type='radio'][name='set_konPas'][value='"+res.set_konPas+"']").prop('checked',true);
				$("input[type='radio'][name='set_konLing'][value='"+res.set_konLing+"']").prop('checked',true);
				$("input[type='radio'][name='cuci_tgn'][value='"+res.cuci_tgn+"']").prop('checked',true);

                $("#keterangan").val(res.keterangan);
                $("#rekomendasi").val(res.rekomendasi);

				$("#btnUpdate").show();
				$("#btnSimpan").hide();
			}else{
				swal({
					title: "Gagal!",
					type: "warning",
					text: "Data Tidak Ada",
					confirmButtonColor: "#3cb878",
				});
			}
		}
	});
}

