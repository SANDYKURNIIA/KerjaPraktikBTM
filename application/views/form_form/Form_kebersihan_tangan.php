function pilih(id){
	$.ajax({
		type: "POST",
		url:"<?= base_url("Formulir_kebersihan_tangan/getData") ?>",
		data: {
			id:id
		},
		beforeSend:function(){
			//Smooth Scroll
			window.scrollTo({
				top:0,
				behavior:'smooth'
			});
		},
		dataType: "json",
		success: function (res) {
			if(res != 0){
				$("#idP").val(btoa(res.id_form));
                $("#nama").val(res.nama);
                $("#hasil").val(res.hasil);

