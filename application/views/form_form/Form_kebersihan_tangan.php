function hapus(id){
		swal({
			title: "Warning?",
			text: "Apakah kamu yakin menghapus data ini?",
			type: "warning",
			showCancelButton: true,
			confirmButtonColor: "#3cb878",
			confirmButtonText: "Yakin",
			cancelButtonText: "Batal",
			closeOnConfirm: false
		},function(){
			$().ready(function(){
				$.ajax({
					url:"<?= base_url("Formulir_kebersihan_tangan/delete") ?>",
					method:"POST",
					dataType: "json",
					data:{
						id:id,
					},
					complete:function(data){
						if(data.status == 200){
							swal({
								title: "good job!",
								type: "success",
								text: "Data Berhasil dihapus",
								confirmButtonColor: "#3cb878",
							});
							$('#datables').DataTable().ajax.reload();
						}else{
							swal({
								title: "Gagal!",
								type: "warning",
								confirmButtonColor: "#3cb878",
							});
						}
					}
				});
			});
		});
		return false;
	}

